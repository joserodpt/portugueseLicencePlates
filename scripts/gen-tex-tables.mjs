// Builds the LaTeX annex tables from data/*.json, one set per language, into
// docs/generated/{pt,en}/. The web app reads the same JSON, so the PDF and the
// app cannot drift apart. Run: npm run docs:tables
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = (name) => JSON.parse(readFileSync(join(root, "data", `${name}.json`), "utf8"));

const esc = (s) =>
  String(s)
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([&%$#_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");
const code = (s) => `\\code{${esc(s)}}`;
const photos = (list = []) => list.map((p) => `\\tablephoto{${p}}`).join(" ");
const mark = (item) => (item.verified === false ? "\\unverified" : "");

const T = {
  pt: {
    code: "Código", name: "Nome", district: "Distrito / Região", photo: "Foto", fn: "Função",
    country: "País / Organização", kind: "Tipo", pairs: "Grupos", since: "Desde", municipality: "Município",
    series: "Série", format: "Formato", period: "Período", number: "Número", registered: "Início de registo",
    noPhoto: "\\textit{sem fotografia}", status: "Estatuto",
    kinds: { island: "Ilhas", "temporary-import": "Importação temporária", regional: "Serviço regional", "ex-colony": "Antigas colónias", military: "Militar", import: "Importação", diplomatic: "Diplomático", state: "Estado" },
    zone: "Zona (até início dos anos 80)",
  },
  en: {
    code: "Code", name: "Name", district: "District / Region", photo: "Photo", fn: "Function",
    country: "Country / Organisation", kind: "Type", pairs: "Pairs", since: "Since", municipality: "Municipality",
    series: "Series", format: "Format", period: "Period", number: "Number", registered: "Registered from",
    noPhoto: "\\textit{no photo}", status: "Status",
    kinds: { island: "Islands", "temporary-import": "Temporary import", regional: "Regional office", "ex-colony": "Former colonies", military: "Military", import: "Import", diplomatic: "Diplomatic", state: "State" },
    zone: "Zone (until the early 1980s)",
  },
};

function longtable(spec, head, rows) {
  return [
    `\\begin{longtable}{${spec}}`,
    "\\toprule",
    head.map((h) => `\\textbf{${h}}`).join(" & ") + " \\\\",
    "\\midrule\\endhead",
    "\\bottomrule\\endfoot",
    ...rows.map((r) => r.join(" & ") + " \\\\"),
    "\\end{longtable}",
    "",
  ].join("\n");
}

/** A compact multi-column list: "CODE  Name" per line. */
function columns(n, rows) {
  return [
    `\\begin{multicols}{${n}}\\small\\raggedright`,
    ...rows.map(([c, name]) => `\\noindent ${c}\\quad ${name}\\par`),
    "\\end{multicols}",
    "",
  ].join("\n");
}

for (const lang of ["pt", "en"]) {
  const t = T[lang];
  const out = join(root, "docs", "generated", lang);
  mkdirSync(out, { recursive: true });
  const write = (name, body) =>
    writeFileSync(join(out, `${name}.tex`), `% Generated by scripts/gen-tex-tables.mjs from data/. Do not edit.\n${body}`);

  write(
    "districts",
    longtable(
      "@{}l p{0.36\\linewidth} p{0.44\\linewidth}@{}",
      [t.code, t.district, t.photo],
      data("districts").map((d) => [code(d.code), esc(d.name[lang]) + mark(d), d.photos ? photos(d.photos) : t.noPhoto]),
    ),
  );

  write(
    "gnr",
    longtable(
      "@{}l l l@{}",
      [t.code, t.fn, t.photo],
      data("gnr-functions").map((g) => [code(g.code), esc(g.name[lang]), g.photos ? photos(g.photos) : t.noPhoto]),
    ),
  );

  write(
    "municipalities",
    columns(
      2,
      data("municipalities").map((m) => [code(m.code), esc(m.name) + mark(m)]),
    ),
  );

  const dip = data("diplomatic-codes");
  const collator = new Intl.Collator(lang === "pt" ? "pt-PT" : "en");
  write(
    "diplomatic",
    longtable("@{}l l@{}", [t.code, t.status], dip.statuses.map((s) => [code(s.code), esc(s.name[lang])])) +
      columns(
         3,
        [...dip.countries]
          .sort((a, b) => collator.compare(a.name[lang], b.name[lang]))
          .map((c) => [code(c.code), esc(c.name[lang])]),
      ),
  );

  const groups = data("letter-groups");
  write(
    "letter-groups",
    longtable(
      "@{}p{0.2\\linewidth} p{0.3\\linewidth} p{0.42\\linewidth}@{}",
      [t.pairs, t.kind, t.name],
      [
        ...groups.zones1937.map((z) => [`${code(z.from)}–${code(z.to)}`, t.zone, esc(z.name[lang])]),
        ...groups.groups1937.map((g) => [
          g.pairs.map(code).join(", "),
          t.kinds[g.kind],
          esc(g.name[lang]) + (g.since ? ` (${g.since})` : "") + mark(g),
        ]),
        ...groups.groups1992.map((g) => [
          g.pairs.map(code).join(", "),
          `${t.kinds[g.kind]} (00-00-XX)`,
          esc(g.name[lang]) + mark(g),
        ]),
      ],
    ),
  );

  write(
    "series",
    longtable(
      "@{}p{0.42\\linewidth} p{0.34\\linewidth} l@{}",
      [t.series, t.format, t.period],
      data("series").map((s) => [
        esc(s.name[lang]),
        s.format.split(" / ").map(code).join(" / "),
        [s.from?.slice(0, 4), s.to ? s.to.slice(0, 4) : "…"].filter(Boolean).join("–"),
      ]),
    ),
  );

  write(
    "trailer-lisbon",
    longtable(
      "@{}l l@{}",
      [t.number, t.registered],
      data("trailer-lisbon").map((r) => [code(`L-${r.from}`), esc(r.period[lang])]),
    ),
  );

  write(
    "export",
    columns(2, data("export-customs").map((c) => [code(c.code), esc(c.name[lang])])),
  );

  const sources = data("sources");
  write(
    "sources",
    [
      "\\begin{itemize}",
      ...Object.values(sources).map((s) => `\\item ${esc(s.title)}${s.url ? ` \\\\ \\url{${s.url}}` : ""}`),
      "\\end{itemize}",
      "",
    ].join("\n"),
  );
}
